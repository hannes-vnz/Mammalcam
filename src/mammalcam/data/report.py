"""Write a Markdown overview of the dataset and the splits.

Usage:
    python -m mammalcam.data.report [--out reports/01_dataset.md]

Needs the split CSVs from ``python -m mammalcam.data.split``.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from mammalcam.data.cct import DEFAULT_ANN_DIR, EMPTY, MULTI, load_cct
from mammalcam.data.split import SPLITS, overlap


def md_table(df: pd.DataFrame) -> str:
    return df.to_markdown()


def build_report(images: pd.DataFrame, ann: pd.DataFrame, splits: dict[str, pd.Series]) -> str:
    n = len(images)
    animal = ann[~ann.category.isin([EMPTY])]
    lines = ["# CCT20: dataset overview", "",
             "Generated by `python -m mammalcam.data.report`. Do not edit by hand.", "",
             "## Totals", "",
             f"- Images: {n:,}",
             f"- Camera locations: {images.location.nunique()}",
             f"- Sequences (bursts): {images.seq_id.nunique():,}",
             f"- Empty images: {(images.label == EMPTY).sum():,} ({(images.label == EMPTY).mean():.1%})",
             f"- Images with more than one animal class: {(images.label == MULTI).sum()}",
             f"- Animal annotations: {len(animal):,}, of which with bounding box: "
             f"{animal.bbox.notna().sum():,} ({animal.bbox.notna().mean():.1%})",
             f"- Capture dates: {images.date_captured.min():%Y-%m-%d} to {images.date_captured.max():%Y-%m-%d}",
             ""]

    per_class = images.groupby("label").agg(images=("image_id", "size"), locations=("location", "nunique"),
                                            sequences=("seq_id", "nunique"))
    per_class["share"] = (per_class.images / n).map("{:.1%}".format)
    lines += ["## Images per class", "", md_table(per_class.sort_values("images", ascending=False)), ""]

    frames = images.groupby("seq_id").size().value_counts().sort_index()
    mixed = (images[images.label != MULTI].groupby("seq_id").label.nunique() > 1).sum()
    lines += ["## Sequences", "",
              "Frames per sequence (number of sequences):", "",
              md_table(frames.rename_axis("frames").to_frame("sequences")), "",
              f"Sequences whose frames carry different labels: {mixed}", ""]

    lines += ["## Images per class and location", "",
              md_table(pd.crosstab(images.label, images.location)), ""]

    rows = {}
    for name, split in splits.items():
        counts = split.value_counts().reindex(SPLITS)
        rows[name] = {**{s: int(counts[s]) for s in SPLITS},
                      "shared locations": overlap(images, split, "location")["n_shared"],
                      "shared sequences": overlap(images, split, "seq_id")["n_shared"]}
    lines += ["## Splits", "",
              "Same number of images per part in every strategy. Only `location` is used for reported results.", "",
              md_table(pd.DataFrame(rows).T), ""]

    loc = splits["location"]
    lines += ["### Location split: locations per part", ""]
    for s in SPLITS:
        lines.append(f"- {s}: {sorted(images.location[loc == s].unique().tolist())}")
    lines += ["", "### Location split: images per class", "",
              md_table(pd.crosstab(images.label, loc)[list(SPLITS)]), ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ann-dir", type=Path, default=DEFAULT_ANN_DIR)
    parser.add_argument("--splits", type=Path, default=Path("data/splits"))
    parser.add_argument("--out", type=Path, default=Path("reports/01_dataset.md"))
    args = parser.parse_args(argv)

    images, ann = load_cct(args.ann_dir)
    splits = {}
    for name in ("location", "random_sequence", "random_image"):
        df = pd.read_csv(args.splits / f"{name}.csv").set_index("image_id")
        splits[name] = images.image_id.map(df.split)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build_report(images, ann, splits))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
