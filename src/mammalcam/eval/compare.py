"""All models side by side on the same test images (camera cross-validation).

Usage:
    python -m mammalcam.eval.compare

Reads whatever prediction files exist:
- data/predictions/classify_test.csv   linear probes (full image, crops)
- data/predictions/finetune_test.csv   fine-tuned crop model (outputs/finetune/predictions.csv from the notebook)
- data/predictions/speciesnet_test.csv SpeciesNet

Writes reports/07_comparison.md.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from mammalcam.eval import metrics
from mammalcam.models.baseline import load_classes

PRED = Path("data/predictions")


def collect(pred_dir: Path = PRED) -> pd.DataFrame:
    """One row per test image, one column per model; missing models are left out."""
    probe = pd.read_csv(pred_dir / "classify_test.csv")
    probe = probe[probe.evaluation.str.startswith("cv_fold")]
    df = probe.rename(columns={
        "full_image": "full image (probe)", "full_sequence": "full image + burst (probe)",
        "crops_image": "crops (probe)", "crops_sequence": "crops + burst (probe)"})
    df = df[["image_id", "seq_id", "location", "label", "evaluation", "full image (probe)",
             "full image + burst (probe)", "crops (probe)", "crops + burst (probe)"]]
    ft = pred_dir / "finetune_test.csv"
    if ft.exists():
        f = pd.read_csv(ft)[["image_id", "crops_image", "crops_sequence"]].rename(columns={
            "crops_image": "crops (fine-tuned)", "crops_sequence": "crops + burst (fine-tuned)"})
        df = df.merge(f, on="image_id", how="left")
    sn = pred_dir / "speciesnet_test.csv"
    if sn.exists():
        s = pd.read_csv(sn)[["image_id", "speciesnet", "speciesnet_burst"]].rename(columns={
            "speciesnet": "SpeciesNet", "speciesnet_burst": "SpeciesNet + burst"})
        df = df.merge(s, on="image_id", how="left")
    return df


def model_columns(df: pd.DataFrame) -> list[str]:
    return [c for c in df.columns if c not in ("image_id", "seq_id", "location", "label", "evaluation")]


def overall(df: pd.DataFrame, classes: list[str]) -> pd.DataFrame:
    rows = {}
    for col in model_columns(df):
        sub = df.dropna(subset=[col])
        folds = [metrics.summary(g.label, g[col], classes) for _, g in sub.groupby("evaluation")]
        pooled = metrics.summary(sub.label, sub[col], classes)
        rows[col] = {
            "test images": pooled["n"],
            "accuracy": pooled["accuracy"],
            "macro-F1": pooled["macro_f1"],
            "accuracy per fold": f"{np.mean([f['accuracy'] for f in folds]):.3f} ± "
                                 f"{np.std([f['accuracy'] for f in folds]):.3f}",
        }
    return pd.DataFrame(rows).T


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=Path("reports/07_comparison.md"))
    args = parser.parse_args(argv)

    classes = load_classes()
    df = collect()
    cols = model_columns(df)
    per_class = pd.DataFrame({c: metrics.per_class(df.dropna(subset=[c]).label, df.dropna(subset=[c])[c],
                                                   classes).f1 for c in cols if "burst" in c})
    per_class["support"] = df.groupby("label").size()
    per_cam = pd.DataFrame({c: df.dropna(subset=[c]).assign(ok=lambda d: d.label == d[c])
                           .groupby("location").ok.mean() for c in cols if "burst" in c})
    missing = [m for m in ("crops (fine-tuned)", "SpeciesNet") if m not in cols]
    lines = [
        "# All models on the same test images", "",
        "Generated by `python -m mammalcam.eval.compare`. Do not edit by hand.", "",
        "Own models: camera cross-validation (5 camera groups, each camera tested once with a model that never "
        "saw it). SpeciesNet: pretrained, no training on these cameras. All crop models use the same MegaDetector "
        "boxes; an image without detection counts as wrong.", "",
    ]
    if missing:
        lines += [f"Not available yet: {', '.join(missing)}.", ""]
    lines += [
        "## Overall", "", overall(df, classes).to_markdown(floatfmt=".3f"), "",
        "## Per class F1 (with burst averaging)", "",
        per_class.sort_values("support", ascending=False).to_markdown(floatfmt=".3f"), "",
        "## Accuracy per camera (with burst averaging)", "", per_cam.to_markdown(floatfmt=".3f"), "",
    ]
    args.out.write_text("\n".join(lines))
    print(overall(df, classes)[["accuracy", "macro-F1"]].round(3))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
