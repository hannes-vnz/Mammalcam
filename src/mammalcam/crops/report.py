"""Markdown overview of the crops.

Usage:
    python -m mammalcam.crops.report [--out reports/03_crops.md]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from mammalcam.crops.make_crops import NO_CROP_LABELS
from mammalcam.data.cct import DEFAULT_ANN_DIR, load_cct
from mammalcam.data.split import SPLITS


def build_report(crops: pd.DataFrame, images: pd.DataFrame) -> str:
    animal = images[~images.label.isin(NO_CROP_LABELS)]
    no_crop = animal[~animal.image_id.isin(crops.image_id)]
    per_image = crops.groupby("image_id").size().value_counts().sort_index()

    coverage = pd.DataFrame({
        "animal images": animal.groupby("label").size(),
        "without crop": no_crop.groupby("label").size(),
    }).fillna(0).astype(int)
    coverage["share without crop"] = (coverage["without crop"] / coverage["animal images"]).map("{:.1%}".format)

    by_split = pd.crosstab(crops.label, crops.split_location)[list(SPLITS)]
    by_split["total"] = by_split.sum(axis=1)

    lines = [
        "# CCT20: animal crops", "",
        "Generated by `python -m mammalcam.crops.report`. Do not edit by hand.", "",
        f"- Crops: {len(crops):,} from {crops.image_id.nunique():,} images",
        f"- Boxes: LILA's precomputed MegaDetector v5a results, animal detections with confidence ≥ "
        f"{crops.conf.min():.2f}",
        f"- Label source: {(crops.source == 'box_match').sum():,} confirmed by an annotated box, "
        f"{(crops.source == 'image_label').sum():,} from the image label only (no annotated box on the image)",
        f"- Animal images without any crop: {len(no_crop):,} of {len(animal):,} "
        f"({len(no_crop) / len(animal):.1%}), mostly burst frames after the animal has left", "",
        "## Crops per class and location split", "",
        by_split.sort_values("total", ascending=False).to_markdown(), "",
        "## Crops per image", "",
        per_image.rename_axis("crops").to_frame("images").to_markdown(), "",
        "## Animal images without a crop", "",
        coverage.to_markdown(), "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ann-dir", type=Path, default=DEFAULT_ANN_DIR)
    parser.add_argument("--crops", type=Path, default=Path("data/crops/crops.csv"))
    parser.add_argument("--out", type=Path, default=Path("reports/03_crops.md"))
    args = parser.parse_args(argv)

    images, _ = load_cct(args.ann_dir)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build_report(pd.read_csv(args.crops), images))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
