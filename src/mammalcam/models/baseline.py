"""Baseline: species classifier on full images, without MegaDetector crops.

Usage:
    python -m mammalcam.models.baseline [--workers 4]

Frozen pretrained backbone + logistic regression (linear probe), trained
once per split strategy on the same embeddings. Uses the same classes as the
crop classifier (configs/classes_cct20.json) and only images with exactly
one of these species, so the two can be compared on the same test images.

Writes reports/results/baseline.json and reports/04_baseline.md;
predictions go to data/predictions/.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

from mammalcam.data.cct import DEFAULT_ANN_DIR, DEFAULT_IMG_DIR, load_cct
from mammalcam.eval import metrics
from mammalcam.models import features, linear_probe

STRATEGIES = ("location", "random_sequence", "random_image")
CLASSES_FILE = Path("configs/classes_cct20.json")


def load_classes(path: Path = CLASSES_FILE) -> list[str]:
    return json.loads(path.read_text())["classes"]


def select_images(images: pd.DataFrame, classes: list[str]) -> pd.DataFrame:
    """Images whose single label is one of the classifier classes."""
    return images[images.label.isin(classes)].sort_values("image_id").reset_index(drop=True)


def run_strategy(x, table: pd.DataFrame, split: pd.Series, classes: list[str]) -> tuple[dict, pd.DataFrame]:
    """Fit on train, pick C on val, evaluate on test. Returns (results, test predictions)."""
    parts = {s: (split == s).values for s in ("train", "val", "test")}
    y = table.label.values
    model, c_scores = linear_probe.fit(x[parts["train"]], y[parts["train"]], x[parts["val"]], y[parts["val"]])
    pred = model.predict(x[parts["test"]])
    y_test = y[parts["test"]]
    results = {
        "test": metrics.summary(y_test, pred, classes),
        "val_macro_f1_by_C": {str(k): v for k, v in c_scores.items()},
        "chosen_C": float(model[-1].C),
        "per_class": metrics.per_class(y_test, pred, classes).round(4).to_dict(orient="index"),
        "confusion": metrics.confusion(y_test, pred, classes).to_dict(orient="split"),
    }
    preds = table.loc[parts["test"], ["image_id", "location", "label"]].assign(pred=pred)
    return results, preds


def build_report(results: dict, backbone: str, n_images: int) -> str:
    rows = {name: {"test images": r["test"]["n"], "accuracy": r["test"]["accuracy"],
                   "macro-F1": r["test"]["macro_f1"], "C": r["chosen_C"]} for name, r in results.items()}
    table = pd.DataFrame(rows).T
    loc = results["location"]
    per_class = pd.DataFrame(loc["per_class"]).T
    cm = loc["confusion"]
    lines = [
        "# Baseline: full-image classifier", "",
        "Generated by `python -m mammalcam.models.baseline`. Do not edit by hand.", "",
        f"- Input: whole image resized to 224×224, no MegaDetector crop ({n_images:,} images with exactly one "
        "of the classifier classes)",
        f"- Model: frozen `{backbone}` embeddings + logistic regression (balanced class weights, "
        "C chosen by validation macro-F1)",
        "- Same embeddings for every split strategy, so differences come from the split alone.", "",
        "## Test results by split strategy", "",
        table.to_markdown(floatfmt=".3f"), "",
        "Only `location` measures performance on unseen cameras. The random splits show how much a careless "
        "split would overestimate it.", "",
        "## Location split: per class", "",
        per_class.sort_values("support", ascending=False).to_markdown(floatfmt=".3f"), "",
        "## Location split: confusion matrix (rows true, columns predicted)", "",
        pd.DataFrame(cm["data"], index=cm["index"], columns=cm["columns"]).to_markdown(), "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ann-dir", type=Path, default=DEFAULT_ANN_DIR)
    parser.add_argument("--img-dir", type=Path, default=DEFAULT_IMG_DIR)
    parser.add_argument("--splits", type=Path, default=Path("data/splits"))
    parser.add_argument("--backbone", default=features.DEFAULT_BACKBONE)
    parser.add_argument("--workers", type=int, default=4)
    args = parser.parse_args(argv)

    classes = load_classes()
    images, _ = load_cct(args.ann_dir)
    table = select_images(images, classes)
    x = features.cached("full_images", table, "file_name", args.img_dir, backbone=args.backbone,
                        workers=args.workers)

    results, preds = {}, []
    for name in STRATEGIES:
        split = table.image_id.map(pd.read_csv(args.splits / f"{name}.csv").set_index("image_id").split)
        results[name], p = run_strategy(x, table, split, classes)
        preds.append(p.assign(strategy=name))
        print(f"{name:16s}", results[name]["test"])

    Path("reports/results").mkdir(parents=True, exist_ok=True)
    Path("reports/results/baseline.json").write_text(json.dumps(
        {"backbone": args.backbone, "classes": classes, "results": results}, indent=2))
    Path("data/predictions").mkdir(parents=True, exist_ok=True)
    pd.concat(preds).to_csv("data/predictions/baseline_test.csv", index=False)
    Path("reports/04_baseline.md").write_text(build_report(results, args.backbone, len(table)))
    print("wrote reports/04_baseline.md")


if __name__ == "__main__":
    main()
